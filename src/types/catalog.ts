export interface CatalogItem {
    id: string;
    orgId: string;
    name: string; // ชื่อสินค้า / วัสดุ / บริการ
    code?: string; // รหัสสินค้า / SKU / รหัสอ้างอิง
    category: CatalogCategory | string; // หมวดหมู่ / ประเภท
    unitPrice: number; // ราคาต่อหน่วย (บาท)
    unit: string; // หน่วยนับ (เช่น ถุง, ตร.ม., ชิ้น)
    storeId?: string; // ID ร้านค้าจาก Store / Vendor ในระบบ (ถ้าเลือกจากระบบ)
    storeName?: string; // ร้านค้า / ตัวแทนจำหน่าย / แหล่งซื้อ
    storePhone?: string; // เบอร์โทรติดต่อร้านค้า
    storeLocation?: string; // ที่ตั้งร้าน / สาขา / ที่อยู่
    storeMapUrl?: string; // ลิงก์ Google Maps ร้านค้า
    photos: string[]; // อัลบั้มรูปภาพสินค้า/วัสดุ
    description?: string; // สเปค / รายละเอียด / บันทึกเพิ่มเติม
    projectId?: string; // โครงการหลักที่เคยใช้ (ถ้ามี)
    projectName?: string; // ชื่อโครงการหลักที่เคยใช้
    projectIds?: string[]; // Array ของ ID โครงการที่ Tag ว่าใช้สินค้านี้
    projectNames?: string[]; // Array ของชื่อโครงการที่ Tag ว่าใช้สินค้านี้
    lastPurchasedDate?: string; // วันที่สั่งซื้อหรือสำรวจล่าสุด
    createdBy: string; // ID ผู้บันทึก (Guest, Staff, Admin)
    createdByName?: string; // ชื่อผู้บันทึก
    createdByRole?: string; // บทบาทผู้บันทึก
    createdByAvatar?: string; // รูปโปรไฟล์ผู้บันทึก
    createdAt: string;
    updatedAt: string;
}
